#!/usr/bin/env python3
"""Emit src/privacy/patterns.zig: every regex (pattern + flags) and word list the gates use, read from the LIVE Python
reference module (~/reference_filters.py) so nothing is transcribed by hand. Read-only import.
Run: python3 tests/phase3/gen_patterns.py > src/privacy/patterns.zig"""
import os, re, sys, hashlib
sys.path.insert(0, os.path.expanduser("~"))
import reference_filters as F

def zs(s):
    out = []
    for ch in s:
        o = ord(ch)
        if ch == "\\": out.append("\\\\")
        elif ch == "\"": out.append("\\\"")
        elif o < 0x20 or o == 0x7f: out.append("\\x%02x" % o)
        else: out.append(ch)
    return "\"" + "".join(out) + "\""

def pat(name, rx):
    bad = rx.flags & ~(re.I | re.S | re.U)
    assert not bad, (name, rx.flags)
    return "pub const %s = P{ .pat = %s, .i = %s, .s = %s };\n" % (name, zs(rx.pattern), str(bool(rx.flags & re.I)).lower(), str(bool(rx.flags & re.S)).lower())

src = open(F.__file__, "rb").read()
w = sys.stdout.write
w("//! GENERATED by tests/phase3/gen_patterns.py from %s (sha256 %s). Do not edit; regenerate.\n" % (os.path.basename(F.__file__), hashlib.sha256(src).hexdigest()[:16]))
w("pub const P = struct { pat: []const u8, i: bool, s: bool };\n")
w("pub const source_sha256_16 = %s;\n" % zs(hashlib.sha256(src).hexdigest()[:16]))
for name, attr in [("self_echo", "_SELF_ECHO_RE"), ("first_person", "_FIRST_PERSON_NARRATION_RE"), ("self_echo_lead", "_SELF_ECHO_LEAD_RE"),
                   ("assistant_tag", "_ASSISTANT_TAG_RE"), ("correction", "_CORRECTION_RE"), ("dated", "_DATED_RE"), ("durable", "_DURABLE_RE"),
                   ("transcript_prefix", "_TRANSCRIPT_PREFIX_RE"), ("empty_fragment", "_EMPTY_FRAGMENT_RE"), ("clock_heading", "_CLOCK_HEADING_RE"),
                   ("tool_log", "_TOOL_LOG_RE"), ("tool_log2", "_TOOL_LOG_RE2"), ("tool_rewrite", "_TOOL_LOG_REWRITE_RE"),
                   ("tool_rewrite_path", "_TOOL_LOG_REWRITE_PATH_RE"), ("tool_rewrite_at", "_TOOL_LOG_REWRITE_AT_RE"), ("file_meta", "_FILE_META_RE"),
                   ("toolu", "_TOOLU_RE"), ("money", "_MONEY_RE"), ("supersession_cue", "_SUPERSESSION_CUE_RE"), ("clause", "_CLAUSE_RE"),
                   ("kw_tok", "_KW_TOK"), ("wd_before", "_WD_BEFORE"), ("wd_after", "_WD_AFTER"), ("wd_ny", "_WD_NY"), ("line_date", "_LINE_DATE"),
                   ("word", "_WORD_RE"), ("med_cue", "_MED_CUE_RE"), ("sent_split", "_SENT_SPLIT_RE"), ("mt_labels", "_MT_LABELS_RE"),
                   ("mt_start", "_MT_START_RE"), ("mt_ready", "_MT_READY_PROBE_RE"), ("mt_session_end", "_MT_SESSION_END_RE"),
                   ("priv_open", "_PRIV_OPEN_RE"), ("priv_span", "_PRIV_SPAN_RE")]:
    w(pat(name, getattr(F, attr)))
w("pub const rel = [_]struct { p: P, off: i32 }{" + ",".join("%s.{ .p = P{ .pat = %s, .i = %s, .s = %s }, .off = %d }" % ("", zs(rx.pattern), str(bool(rx.flags & re.I)).lower(), str(bool(rx.flags & re.S)).lower(), off) for rx, off in F._REL) + "};\n")
w("pub const family = [_]struct { name: []const u8, p: P }{" + ",".join(".{ .name = %s, .p = P{ .pat = %s, .i = %s, .s = false } }" % (zs(k), zs(rx.pattern), str(bool(rx.flags & re.I)).lower()) for k, rx in F._FAMILY_NAME_RE.items()) + "};\n")
w("pub const alias = [_]struct { name: []const u8, p: P }{" + ",".join(".{ .name = %s, .p = P{ .pat = %s, .i = %s, .s = false } }" % (zs(k), zs(rx.pattern), str(bool(rx.flags & re.I)).lower()) for k, rx in F._TARGET_ALIAS_RE.items()) + "};\n")
w("pub const transcript_markers = [_][]const u8{" + ",".join(zs(m) for m in F._TRANSCRIPT_MARKERS) + "};\n")
w("pub const mt_bare = [_][]const u8{" + ",".join(zs(m) for m in sorted(F._MT_BARE)) + "};\n")
w("pub const kw_stop = [_][]const u8{" + ",".join(zs(m) for m in sorted(F._KW_STOP)) + "};\n")
w("pub const wdn = [_][]const u8{" + ",".join(zs(m) for m in F._WDN) + "};\n")
assert F._WD == {"mon": 0, "tue": 1, "wed": 2, "thu": 3, "fri": 4, "sat": 5, "sun": 6}
assert list(F._MONTHS) == ["jan", "feb", "mar", "apr", "may", "jun", "jul", "aug", "sep", "oct", "nov", "dec"]
w("pub const private_mark = %s;\n" % zs(F.PRIVATE_MARK))

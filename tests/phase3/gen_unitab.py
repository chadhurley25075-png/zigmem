#!/usr/bin/env python3
"""Generate src/privacy/unitab.zig from THIS Python (the reference interpreter): \\w \\d \\s tables, sre IGNORECASE
equivalence classes (simple lowercase + _ignorecase_fixes, exactly what sre compiles), str.lower() full mappings,
decimal digit values. Run: python3 tests/phase3/gen_unitab.py > src/privacy/unitab.zig"""
import sys, _sre
try:
    from re import _compiler as C
except ImportError:
    import sre_compile as C
fixes = getattr(C, "_ignorecase_fixes", None) or C._EXTRA_CASES
MAX = 0x110000

def ranges(pred):
    out, start = [], None
    for cp in range(MAX):
        ok = pred(cp)
        if ok and start is None: start = cp
        if not ok and start is not None: out.append((start, cp - 1)); start = None
    if start is not None: out.append((start, MAX - 1))
    return out

def safe(f):
    def g(cp):
        if 0xD800 <= cp <= 0xDFFF: return False
        return f(chr(cp))
    return g

word = ranges(safe(lambda c: c.isalnum() or c == "_"))
dec = ranges(safe(lambda c: c.isdecimal()))
space = ranges(safe(lambda c: c.isspace()))
# union-find over (cp ~ unicode_tolower(cp)) and the sre fixes
parent = {}
def find(x):
    while parent.get(x, x) != x:
        parent[x] = parent.get(parent[x], parent[x]); x = parent[x]
    return x
def union(a, b):
    ra, rb = find(a), find(b)
    if ra != rb: parent[max(ra, rb)] = min(ra, rb)
for cp in range(MAX):
    lo = _sre.unicode_tolower(cp)
    if lo != cp: union(cp, lo)
for k, vs in fixes.items():
    for v in vs: union(k, v)
groups = {}
for cp in list(parent.keys()) + [v for v in parent.values()]:
    groups.setdefault(find(cp), set()).add(cp)
groups = {r: sorted(m) for r, m in groups.items() if len(m) > 1}
fold = sorted((cp, r) for r, m in groups.items() for cp in m)
lower = []
for cp in range(MAX):
    if 0xD800 <= cp <= 0xDFFF: continue
    l = chr(cp).lower()
    if l != chr(cp): lower.append((cp, [ord(x) for x in l]))
digval = []
for a, b in dec:
    for cp in range(a, b + 1):
        digval.append((cp, int(chr(cp))))
w = sys.stdout.write
w("//! GENERATED by tests/phase3/gen_unitab.py from Python %s: Unicode tables for the sre-compatible engine. Do not edit.\n" % sys.version.split()[0])
w("pub const R = [2]u21;\n")
for name, rs in (("word", word), ("decimal", dec), ("space", space)):
    w("pub const %s = [_]R{" % name + ",".join(".{%d,%d}" % r for r in rs) + "};\n")
w("/// (codepoint, canonical member) for every codepoint whose IGNORECASE class has more than one member, sorted.\n")
w("pub const fold = [_]R{" + ",".join(".{%d,%d}" % p for p in fold) + "};\n")
w("/// members of each class, keyed by canonical (first element), sorted by canonical.\n")
w("pub const groups = [_][]const u21{" + ",".join("&.{" + ",".join(str(x) for x in groups[r]) + "}" for r in sorted(groups)) + "};\n")
w("/// str.lower() where it differs: (cp, first, second-or-0)\n")
w("pub const lower = [_][3]u21{" + ",".join(".{%d,%d,%d}" % (cp, l[0], l[1] if len(l) > 1 else 0) for cp, l in lower) + "};\n")
assert all(len(l) <= 2 for _, l in lower)
w("pub const digit = [_]R{" + ",".join(".{%d,%d}" % p for p in digval) + "};\n")
